export function glyph(code: number): number[][] {
  const ch = String.fromCharCode(code),
    normalized = ch.normalize("NFD");
  const base = source[ch] ? ch : normalized[0]!;
  const rows = (source[base] ?? source[" "]!)
    .split(" ")
    .map((r) => [...r].map(Number));
  const out = Array.from({ length: 10 }, () => Array<number>(6).fill(0));
  rows.forEach((r, y) =>
    r.forEach((v, x) => {
      out[y + 2]![x] = v;
    }),
  );
  if (normalized.length > 1 && !source[ch]) {
    const accent = normalized.charCodeAt(1);
    if (accent === 0x308) {
      out[0]![1] = 1;
      out[0]![3] = 1;
    } else if (accent === 0x300) {
      out[0]![1] = 1;
      out[1]![2] = 1;
    } else if (accent === 0x302) {
      out[0]![2] = 1;
      out[1]![1] = 1;
      out[1]![3] = 1;
    } else if (accent === 0x303) {
      out[0]![1] = 1;
      out[0]![3] = 1;
      out[1]![2] = 1;
    } else if (accent === 0x30a) {
      out[0]![2] = 1;
      out[1]![1] = 1;
      out[1]![3] = 1;
    } else if (accent === 0x327) {
      out[9]![2] = 1;
      out[9]![1] = 1;
    } else {
      out[0]![3] = 1;
      out[1]![2] = 1;
    }
  }
  return out;
}
export function generateFont(dir: string) {
  const p = new Pixel(128, 160);
  let xml =
    '<font><info face="Willow Ink" size="10"/><common lineHeight="11" base="9" scaleW="128" scaleH="160" pages="1"/><pages><page id="0" file="font.png"/></pages><chars count="224">';
  for (let code = 32; code < 256; code++) {
    const x = ((code - 32) % 16) * 8,
      y = Math.floor((code - 32) / 16) * 11;
    glyph(code).forEach((r, j) =>
      r.forEach((v, i) => {
        if (v) p.dot(x + i, y + j, 31);
      }),
    );
    xml += `<char id="${code}" x="${x}" y="${y}" width="6" height="10" xoffset="0" yoffset="0" xadvance="6" page="0" chnl="15"/>`;
  }
  writeFileSync(`${dir}/font.png`, p.buffer());
  writeFileSync(`${dir}/font.xml`, xml + "</chars></font>");
}

export function generateBoldFont(dir: string) {
  const p = new Pixel(128, 112);
  let xml =
    '<font><info face="Willow Ink Bold" size="8"/><common lineHeight="9" base="7" scaleW="128" scaleH="112" pages="1"/><pages><page id="0" file="font-bold.png"/></pages><chars count="224">';
  for (let code = 32; code < 256; code++) {
    const x = ((code - 32) % 16) * 8,
      y = Math.floor((code - 32) / 16) * 8;
    glyph(code)
      .slice(2, 9)
      .forEach((r, j) =>
        r.forEach((v, i) => {
          if (v) {
            p.dot(x + i, y + j, 31);
            p.dot(x + i + 1, y + j, 31);
          }
        }),
      );
    xml += `<char id="${code}" x="${x}" y="${y}" width="7" height="8" xoffset="0" yoffset="0" xadvance="8" page="0" chnl="15"/>`;
  }
  writeFileSync(`${dir}/font-bold.png`, p.buffer());
  writeFileSync(`${dir}/font-bold.xml`, xml + "</chars></font>");
}
