export function validateCatalog(): void {
  for (const key of Object.keys(catalog) as (keyof typeof catalog)[]) {
    catalogSchemas[key].parse(catalog[key]);
    const ids = catalog[key].map((entry) => entry.id);
    if (new Set(ids).size !== ids.length)
      throw new Error(`Duplicate ID in ${key}`);
  }
  const itemIds = new Set(items.map((entry) => entry.id));
  const mapIds = new Set(maps.map((entry) => entry.id));
  const requireItem = (value: string) => {
    if (!itemIds.has(value)) throw new Error(`Missing item: ${value}`);
  };
  const requireMap = (value: string) => {
    if (!mapIds.has(value)) throw new Error(`Missing map: ${value}`);
  };
  for (const row of [...recipes, ...processedGoods])
    for (const part of row.ingredients) requireItem(part.item);
  for (const row of processedGoods) requireItem(row.machine);
  for (const row of shops) {
    requireMap(row.map);
    for (const stock of row.stock) requireItem(stock.item);
  }
  for (const row of maps)
    for (const link of row.connections) {
      requireMap(link);
      if (!maps.find((map) => map.id === link)?.connections.includes(row.id))
        throw new Error(`One-way map link: ${row.id}/${link}`);
    }
  for (const row of [...fish, ...forage])
    for (const location of row.locations) requireMap(location);
  for (const npc of npcs) {
    requireMap(npc.home);
    if (npc.romanceable && npc.age < 25)
      throw new Error(`Romance age: ${npc.id}`);
    for (const item of [
      ...npc.loved,
      ...npc.liked,
      ...npc.disliked,
      ...npc.hated,
    ])
      requireItem(item);
    for (const route of [
      npc.schedule,
      ...npc.scheduleRules.map((rule) => rule.steps),
    ]) {
      let hour = -1;
      for (const entry of route) {
        requireMap(entry.map);
        const map = maps.find((row) => row.id === entry.map);
        if (
          !map ||
          entry.x >= map.width ||
          entry.y >= map.height ||
          entry.hour <= hour
        )
          throw new Error(`Invalid schedule: ${npc.id}`);
        hour = entry.hour;
      }
    }
  }
  for (const crop of [...crops, ...flowers]) {
    requireItem(crop.id);
    requireItem(`${crop.id}_seed`);
  }
  for (const tree of trees) {
    requireItem(tree.id);
    requireItem(`${tree.id}_sapling`);
  }
}
